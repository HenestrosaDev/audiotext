#!/usr/bin/env bash
# Creates the macOS disk image of Audiotext, where the app can be dragged into the
# Applications folder.
#
# To create it locally, build the app and run this script from the root of the project:
#
#   pyinstaller audiotext.spec --noconfirm
#   packaging/macos/make_dmg.sh
#
# Usage: packaging/macos/make_dmg.sh [app] [output directory]
#   app               The app built by PyInstaller (default: dist/Audiotext.app)
#   output directory  Where the disk image is created (default: dist)
#
# The layout of the window is in dmg_settings.py, and its background in
# dmg-background*.png (generated by make_dmg_background.py), next to this script.

set -euo pipefail

app="${1:-dist/Audiotext.app}"
out_dir="${2:-dist}"

version=$(sed -n 's/^version = "\(.*\)"/\1/p' pyproject.toml | head -n 1)
name="Audiotext-$version-macos-$(uname -m)"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Fails if PyInstaller didn't sign the app properly, which macOS reports as "damaged"
codesign --verify --deep --strict "$app"

# dmgbuild writes the layout of the window without opening Finder, so it also works
# in CI. Only its dependency group is installed, not the ones of the app
mkdir -p "$out_dir"
uv run --locked --only-group dmg dmgbuild \
    -s "$here/dmg_settings.py" \
    -D app="$app" \
    -D here="$here" \
    Audiotext "$out_dir/$name.dmg"

echo "Created $out_dir/$name.dmg"
