"""
The actions of the views of the entries (and of the list of the history). The
ones that only change the data are done by the controllers, which satisfy these
Protocols, while the ones that ask the user first or change what's shown are
done by the window.
"""

from collections.abc import Callable
from dataclasses import dataclass
from datetime import datetime
from enum import Enum
from pathlib import Path
from typing import Protocol

from models.transcript_segment import TranscriptSegment
from utils.env_keys import EnvKeys


class EntryFiles(Protocol):
    """Shows the files of the entries in the file manager."""

    def reveal_entry(self, entry_id: str) -> None: ...
    def open_folder(self, folder: Path) -> None: ...
    def skipped_files_counter(self, entry_id: str) -> Callable[[], int] | None: ...


class TranscriptEditor(Protocol):
    """
    Corrects, summarizes, translates and answers questions about the transcription
    of an entry.
    """

    def save_text(self, entry_id: str, text: str) -> None: ...
    def update_transcript(
        self, entry_id: str, segments: list[TranscriptSegment], text: str
    ) -> None: ...
    def review_transcript(
        self, entry_id: str, segments: list[TranscriptSegment]
    ) -> None: ...
    def save_reviews(self) -> None: ...
    def summarize_entry(self, entry_id: str) -> None: ...
    def is_summarizing(self, entry_id: str) -> bool: ...
    def get_summary_error(self, entry_id: str) -> str: ...
    def ask_question(self, entry_id: str, question: str) -> None: ...
    def get_question(self, entry_id: str) -> str | None: ...
    def get_question_error(self, entry_id: str) -> str: ...
    def clear_questions(self, entry_id: str) -> None: ...
    def translate_entry(
        self, entry_id: str, language: str, provider: str, model: str = ""
    ) -> None: ...
    def start_manual_translation(
        self,
        entry_id: str,
        language: str,
        segments: list[TranscriptSegment] | None = None,
    ) -> None: ...
    def is_translating(self, entry_id: str, language: str) -> bool: ...
    def translating_languages(self, entry_id: str) -> list[str]: ...
    def get_translation_error(self, entry_id: str, language: str) -> str: ...
    def save_translation_text(
        self, entry_id: str, language: str, text: str
    ) -> None: ...
    def update_translation(
        self,
        entry_id: str,
        language: str,
        segments: list[TranscriptSegment],
        text: str,
    ) -> None: ...
    def remove_translation(self, entry_id: str, language: str) -> None: ...


class JobControls(Protocol):
    """Transcribes an entry again or cancels it, and tells how it's going."""

    def retry_entry(self, entry_id: str) -> None: ...
    def retranscribe_folder(self, entry_id: str) -> None: ...
    def retranscribe_files(self, entry_ids: list[str]) -> None: ...
    def cancel_entry(self, entry_id: str) -> None: ...
    def get_progress(self, entry_id: str) -> float | None: ...
    def get_progress_message(self, entry_id: str) -> tuple[str, float | None]: ...
    def get_queue_position(self, entry_id: str) -> int | None: ...
    def is_watch_idle(self, entry_id: str) -> bool: ...
    def get_last_watched_file(self, entry_id: str) -> tuple[str, datetime] | None: ...


class EntryPrompts(Protocol):
    """The actions on an entry that ask the user for a value or a confirmation."""

    def ask_to_rename_entry(self, entry_id: str) -> None: ...
    def ask_for_note(self, entry_id: str) -> None: ...
    def confirm_delete_note(self, entry_id: str) -> None: ...
    def ask_for_tag(self, entry_id: str) -> None: ...
    def confirm_delete_entry(self, entry_id: str) -> None: ...
    def confirm_remove_entries(self, entry_ids: list[str]) -> None: ...


class TranscriptAction(Enum):
    """What to do with a transcription once it's opened, e.g. from its folder."""

    EXPORT = "export"
    SUMMARIZE = "summarize"
    TRANSLATE = "translate"


class Navigator(Protocol):
    """What the views of the entries ask the window to show."""

    def select_entry(self, entry_id: str) -> None: ...
    def open_transcript(self, entry_id: str, action: TranscriptAction) -> None: ...
    def go_back_to_settings(self, entry_id: str) -> None: ...
    def show_preferences(self, tab: str | None = None) -> None: ...
    def set_api_key(self, env_key: EnvKeys) -> None: ...
    def show_status(self, message: str, is_error: bool = False) -> None: ...


@dataclass(frozen=True)
class EntryActions:
    """Everything the views of the entries can do, grouped by who does it."""

    files: EntryFiles
    transcript: TranscriptEditor
    jobs: JobControls
    prompts: EntryPrompts
    window: Navigator
